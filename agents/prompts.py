def get_agent_system_prompt(agent_name: str, context: Optional[Dict[str, Any]] = None) -> str:
    """الحصول على الأمر المعياري للوكيل مع حقن السياق التشغيلي الحي دون استهلاك مفرط للتوكنات."""
    norm_name = str(agent_name).lower().strip()
    # أسماء مرادفة
    alias_map = {
        "modaqeq": "mudaqqiq",
        "mowafaq": "muwaffaq",
    }
    canonical_name = alias_map.get(norm_name, norm_name)
    base_prompt = AGENT_SYSTEM_PROMPTS.get(canonical_name, AGENT_SYSTEM_PROMPTS["seraj"])

    if not context:
        return base_prompt

    context_str = format_compact_odoo_context(context)
    if not context_str:
        return base_prompt

    return f"{base_prompt}\n\n🌐 **السياق التشغيلي الحي لـ Odoo:**\n{context_str}"


def format_compact_odoo_context(context: Optional[Dict[str, Any]] = None) -> str:
    """توليد ملخص سياقي مدمج لبيئة Odoo الحالية (Context Engineering) لتوجيه الوكلاء بدقة واقتصاد في التوكنات."""
    if not context:
        return ""

    lines = []
    comp_name = context.get("company_name") or context.get("company")
    comp_id = context.get("company_id")
    if comp_name or comp_id:
        lines.append(f"• المنشأة الحالية: {comp_name or '—'} (معرف: {comp_id or '—'})")

    conn_id = context.get("connection_id")
    if conn_id:
        lines.append(f"• الاتصال بقاعدة البيانات: {conn_id}")

    # إضافة أسماء الشركات المتاحة بإيجاز
    companies = context.get("companies")
    if isinstance(companies, list) and companies:
        c_names = [c.get("name") for c in companies if isinstance(c, dict) and c.get("name")]
        if c_names:
            preview = ", ".join(c_names[:5])
            if len(c_names) > 5:
                preview += f" (+{len(c_names)-5} أخرى)"
            lines.append(f"• المنشآت المصرح بها: {preview}")

    # إضافة الأقسام المعتمدة بإيجاز
    departments = context.get("departments")
    if isinstance(departments, list) and departments:
        d_names = [d.get("name") for d in departments if isinstance(d, dict) and d.get("name")]
        if d_names:
            preview = ", ".join(d_names[:6])
            if len(d_names) > 6:
                preview += f" (+{len(d_names)-6} أخرى)"
            lines.append(f"• الأقسام النشطة: {preview}")

    # إضافة المسميات المعتمدة بإيجاز
    jobs = context.get("jobs")
    if isinstance(jobs, list) and jobs:
        j_names = [j.get("name") for j in jobs if isinstance(j, dict) and j.get("name")]
        if j_names:
            preview = ", ".join(j_names[:6])
            if len(j_names) > 6:
                preview += f" (+{len(j_names)-6} أخرى)"
            lines.append(f"• المسميات الوظيفية: {preview}")

    return "\n".join(lines)

