async def run_live_scenarios():
    client = TelegramClient(session, app_id, api_hash)
    await client.connect()
    bot = await client.get_entity('odoo_hr_bot')

    # تصفير أي جلسات سابقة
    await client.send_message(bot, "/cancel")
    await asyncio.sleep(1.5)

    results = []

    for sc in SCENARIOS:
        print(f"\n==================================================")
        print(f"🚀 تنفيذ السيناريو {sc['id']}/23: {sc['title']}")
        print(f"💬 إرسال الرسالة إلى سراج: «{sc['prompt']}»")
        
        sent_msg = await client.send_message(bot, sc["prompt"])
        response_text = ""
        
        # انتظر الرد من سراج حتى 20 ثانية كحد أقصى
        for _ in range(10):
            await asyncio.sleep(2)
            messages = await client.get_messages(bot, limit=2)
            if messages and messages[0].id != sent_msg.id and not messages[0].out:
                response_text = messages[0].text
                break
                
        print(f"🤖 رد سراج الحي في التيليقرام:")
        preview = response_text[:180] + ("..." if len(response_text) > 180 else "")
        print(preview if preview else "[لم يتم استلام رد في الوقت المحدد]")
        
        results.append({
            "id": sc["id"],
            "title": sc["title"],
            "prompt": sc["prompt"],
            "response": response_text,
        })
        
        # انتظار بسيط بين السيناريوهات لعدم إغراق التيليقرام
        await asyncio.sleep(1.5)

    with open("tests/live_telegram_results.json", "w", encoding="utf-8") as f:
        json.dump(results, f, ensure_ascii=False, indent=2)

    print(f"\n==================================================")
    print(f"✅ تم تنفيذ جميع الـ 23 سيناريو الحي بنجاح وحفظ الردود في tests/live_telegram_results.json")
    await client.disconnect()

if __name__ == "__main__":
    asyncio.run(run_live_scenarios())
